-- Permissions: menus, sub-menus, role permissions and per-staff restrictions
-- (see specs/build/permissions/permission_spec.md §4).
-- Idempotent. Seeding inserts only rows that don't exist yet — counting deleted ones — so a default an
-- organization deliberately deleted isn't recreated on the next run, while new pages still get their
-- defaults everywhere. Explicit NOT EXISTS (not ON CONFLICT) so re-runs don't consume identity values.

-- 1. Menus (global). MenuKey is the code's name for a menu; MenuType fixes its shape:
--    PAGE  = plain tab that opens its own page (permissions attach to the menu, no sub-menus)
--    GROUP = dropdown whose items are sub-menus (permissions attach to the sub-menus)
ALTER TABLE "sys_menu" ADD COLUMN IF NOT EXISTS "MenuKey" varchar(50);
ALTER TABLE "sys_menu" ADD COLUMN IF NOT EXISTS "MenuType" varchar(5);
ALTER TABLE "sys_menu" ALTER COLUMN "MenuKey" SET NOT NULL;
ALTER TABLE "sys_menu" ALTER COLUMN "MenuType" SET NOT NULL;
ALTER TABLE "sys_menu" DROP CONSTRAINT IF EXISTS "sys_menu_type_check";
ALTER TABLE "sys_menu" ADD CONSTRAINT "sys_menu_type_check" CHECK ("MenuType" IN ('PAGE', 'GROUP'));
CREATE UNIQUE INDEX IF NOT EXISTS "sys_menu_key" ON "sys_menu" ("MenuKey") WHERE "RecordStatus" <> 'D';

-- 2. Sub-menus: the global template (developer-defined, one per real page) ...
CREATE TABLE IF NOT EXISTS "sys_sub_menu" (
    "SubMenuId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MenuId" bigint NOT NULL REFERENCES "sys_menu" ("MenuId"),
    "SubMenuKey" varchar(50) NOT NULL,
    "Label" varchar(50) NOT NULL,
    "Order" bigint NOT NULL,
    "RecordStatus" char(1) NOT NULL,
    "AddedBy" varchar(50) NOT NULL,
    "AddedDate" timestamp NOT NULL,
    "UpdatedBy" varchar(50) NOT NULL,
    "UpdatedDate" timestamp NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "sys_sub_menu_key" ON "sys_sub_menu" ("SubMenuKey") WHERE "RecordStatus" <> 'D';

-- ... and each organization's own copy (label / order / active state per organization).
CREATE TABLE IF NOT EXISTS "sub_menu" (
    "SubMenuId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OrganizationId" bigint NOT NULL REFERENCES "organization" ("OrganizationId") ON DELETE CASCADE,
    "MenuId" bigint NOT NULL REFERENCES "sys_menu" ("MenuId"),
    "SubMenuKey" varchar(50) NOT NULL,
    "Label" varchar(50) NOT NULL,
    "Order" bigint NOT NULL,
    "RecordStatus" char(1) NOT NULL,
    "AddedBy" varchar(50) NOT NULL,
    "AddedDate" timestamp NOT NULL,
    "UpdatedBy" varchar(50) NOT NULL,
    "UpdatedDate" timestamp NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "sub_menu_org_key" ON "sub_menu" ("OrganizationId", "SubMenuKey") WHERE "RecordStatus" <> 'D';
CREATE INDEX IF NOT EXISTS "sub_menu_org_menu_idx" ON "sub_menu" ("OrganizationId", "MenuId");

-- Sub-menus may only belong to GROUP menus.
CREATE OR REPLACE FUNCTION "sub_menu_requires_group_menu"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."RecordStatus" <> 'D' AND NOT EXISTS (
        SELECT 1 FROM "sys_menu" m WHERE m."MenuId" = NEW."MenuId" AND m."MenuType" = 'GROUP'
    ) THEN
        RAISE EXCEPTION 'Sub-menu "%" must belong to a GROUP menu', NEW."SubMenuKey"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sub_menu_group_menu';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "sys_sub_menu_group_menu" ON "sys_sub_menu";
CREATE TRIGGER "sys_sub_menu_group_menu" BEFORE INSERT OR UPDATE ON "sys_sub_menu"
    FOR EACH ROW EXECUTE FUNCTION "sub_menu_requires_group_menu"();
DROP TRIGGER IF EXISTS "sub_menu_group_menu" ON "sub_menu";
CREATE TRIGGER "sub_menu_group_menu" BEFORE INSERT OR UPDATE ON "sub_menu"
    FOR EACH ROW EXECUTE FUNCTION "sub_menu_requires_group_menu"();

-- 3. Role permissions (existing legacy table, empty until now): one row per organization, role and
--    page. Page = a PAGE menu (SubMenuId NULL) or a sub-menu of a GROUP menu (SubMenuId required).
ALTER TABLE "role_permission" ADD COLUMN IF NOT EXISTS "SubMenuId" bigint REFERENCES "sub_menu" ("SubMenuId") ON DELETE CASCADE;
ALTER TABLE "role_permission" ALTER COLUMN "Page" DROP NOT NULL;     -- not used
ALTER TABLE "role_permission" ALTER COLUMN "IsOption" DROP NOT NULL; -- not used
ALTER TABLE "role_permission" ALTER COLUMN "Export" SET DEFAULT '1';
-- SELF = all users' records including mine; ALL = excluding mine (spec §2).
ALTER TABLE "role_permission" ALTER COLUMN "ViewType" SET DEFAULT 'SELF';
CREATE UNIQUE INDEX IF NOT EXISTS "role_permission_page_key"
    ON "role_permission" ("OrganizationId", "RoleId", "MenuId", coalesce("SubMenuId", 0)) WHERE "RecordStatus" <> 'D';
CREATE UNIQUE INDEX IF NOT EXISTS "role_permission_title_key"
    ON "role_permission" ("OrganizationId", lower("Title")) WHERE "RecordStatus" <> 'D';

CREATE OR REPLACE FUNCTION "role_permission_check_page"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    menuType varchar;
BEGIN
    IF NEW."RecordStatus" = 'D' THEN
        RETURN NEW;
    END IF;
    IF NEW."RoleId" = 1 THEN
        RAISE EXCEPTION 'DEVELOPER has every permission; it cannot have role permissions'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'role_permission_not_developer';
    END IF;
    SELECT m."MenuType" INTO menuType FROM "sys_menu" m WHERE m."MenuId" = NEW."MenuId";
    IF menuType IS NULL THEN
        RAISE EXCEPTION 'Menu % does not exist', NEW."MenuId"
            USING ERRCODE = 'foreign_key_violation', CONSTRAINT = 'role_permission_menu';
    ELSIF menuType = 'PAGE' AND NEW."SubMenuId" IS NOT NULL THEN
        RAISE EXCEPTION 'Menu % has no sub-menus', NEW."MenuId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'role_permission_page_menu';
    ELSIF menuType = 'GROUP' AND NOT EXISTS (
        SELECT 1 FROM "sub_menu" s
        WHERE s."SubMenuId" = NEW."SubMenuId" AND s."MenuId" = NEW."MenuId"
          AND s."OrganizationId" = NEW."OrganizationId" AND s."RecordStatus" <> 'D'
    ) THEN
        RAISE EXCEPTION 'A sub-menu of menu % in this organization is required', NEW."MenuId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'role_permission_group_sub_menu';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "role_permission_check_page" ON "role_permission";
CREATE TRIGGER "role_permission_check_page" BEFORE INSERT OR UPDATE ON "role_permission"
    FOR EACH ROW EXECUTE FUNCTION "role_permission_check_page"();

-- A menu can't switch type while it still has sub-menus (GROUP → PAGE) or menu-level permissions
-- (PAGE → GROUP).
CREATE OR REPLACE FUNCTION "sys_menu_check_type_change"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."MenuType" = 'PAGE' AND (
        EXISTS (SELECT 1 FROM "sys_sub_menu" WHERE "MenuId" = NEW."MenuId" AND "RecordStatus" <> 'D') OR
        EXISTS (SELECT 1 FROM "sub_menu" WHERE "MenuId" = NEW."MenuId" AND "RecordStatus" <> 'D')
    ) THEN
        RAISE EXCEPTION 'Menu "%" still has sub-menus', NEW."MenuKey"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sys_menu_type_change';
    ELSIF NEW."MenuType" = 'GROUP' AND EXISTS (
        SELECT 1 FROM "role_permission"
        WHERE "MenuId" = NEW."MenuId" AND "SubMenuId" IS NULL AND "RecordStatus" <> 'D'
    ) THEN
        RAISE EXCEPTION 'Menu "%" still has menu-level permissions', NEW."MenuKey"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sys_menu_type_change';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "sys_menu_check_type_change" ON "sys_menu";
CREATE TRIGGER "sys_menu_check_type_change" BEFORE UPDATE OF "MenuType" ON "sys_menu"
    FOR EACH ROW WHEN (OLD."MenuType" IS DISTINCT FROM NEW."MenuType")
    EXECUTE FUNCTION "sys_menu_check_type_change"();

-- 4. Staff restrictions: per staff member and role permission, which of the role's actions are kept
--    ('1') or switched off for that person ('0'). No row = everything inherited from the role.
CREATE TABLE IF NOT EXISTS "staff_permission" (
    "StaffPermissionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OrganizationId" bigint NOT NULL REFERENCES "organization" ("OrganizationId") ON DELETE CASCADE,
    "LoginId" bigint NOT NULL REFERENCES "login" ("LoginId") ON DELETE CASCADE,
    "RolePermissionId" bigint NOT NULL REFERENCES "role_permission" ("RolePermissionId") ON DELETE CASCADE,
    "IsPageAllow" varchar(1) NOT NULL DEFAULT '1' CHECK ("IsPageAllow" IN ('0', '1')),
    "Add" varchar(1) NOT NULL DEFAULT '1' CHECK ("Add" IN ('0', '1')),
    "Edit" varchar(1) NOT NULL DEFAULT '1' CHECK ("Edit" IN ('0', '1')),
    "Delete" varchar(1) NOT NULL DEFAULT '1' CHECK ("Delete" IN ('0', '1')),
    "Export" varchar(1) NOT NULL DEFAULT '1' CHECK ("Export" IN ('0', '1')),
    "RecordStatus" char(1) NOT NULL,
    "AddedBy" varchar(50) NOT NULL,
    "AddedDate" timestamp NOT NULL,
    "UpdatedBy" varchar(50) NOT NULL,
    "UpdatedDate" timestamp NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "staff_permission_login_key"
    ON "staff_permission" ("LoginId", "RolePermissionId") WHERE "RecordStatus" <> 'D';
CREATE INDEX IF NOT EXISTS "staff_permission_role_permission_idx" ON "staff_permission" ("RolePermissionId");

-- A restriction must concern a staff member of the same organization who holds that permission's role.
CREATE OR REPLACE FUNCTION "staff_permission_check"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."RecordStatus" <> 'D' AND NOT EXISTS (
        SELECT 1 FROM "login" l
        JOIN "role_permission" rp ON rp."RolePermissionId" = NEW."RolePermissionId"
        WHERE l."LoginId" = NEW."LoginId"
          AND l."OrganizationId" = NEW."OrganizationId"
          AND rp."OrganizationId" = NEW."OrganizationId"
          AND rp."RoleId" = l."LoginType"
    ) THEN
        RAISE EXCEPTION 'Staff member % does not hold the role of permission % in organization %',
            NEW."LoginId", NEW."RolePermissionId", NEW."OrganizationId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'staff_permission_role';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "staff_permission_check" ON "staff_permission";
CREATE TRIGGER "staff_permission_check" BEFORE INSERT OR UPDATE ON "staff_permission"
    FOR EACH ROW EXECUTE FUNCTION "staff_permission_check"();

-- 5. Seed: the Staff menu and its "Staff" page.
INSERT INTO "sys_menu" ("Menu", "MenuKey", "MenuType", "Order", "RecordStatus", "AddedBy", "AddedDate", "UpdatedBy", "UpdatedDate")
SELECT 'Staff', 'staff', 'GROUP', 1, 'A', 'SYSTEM', localtimestamp, 'SYSTEM', localtimestamp
WHERE NOT EXISTS (SELECT 1 FROM "sys_menu" WHERE "MenuKey" = 'staff');

INSERT INTO "sys_sub_menu" ("MenuId", "SubMenuKey", "Label", "Order", "RecordStatus", "AddedBy", "AddedDate", "UpdatedBy", "UpdatedDate")
SELECT m."MenuId", 'staff-list', 'Staff', 1, 'A', 'SYSTEM', localtimestamp, 'SYSTEM', localtimestamp
FROM "sys_menu" m
WHERE m."MenuKey" = 'staff'
  AND NOT EXISTS (SELECT 1 FROM "sys_sub_menu" WHERE "SubMenuKey" = 'staff-list');

-- 6. Per-organization defaults.
-- Copies the template sub-menus the organization has never had (deleted ones are not re-added).
DROP ROUTINE IF EXISTS "assign_default_sub_menus";
CREATE OR REPLACE PROCEDURE "assign_default_sub_menus"(varOrganizationId bigint)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO "sub_menu" ("OrganizationId", "MenuId", "SubMenuKey", "Label", "Order", "RecordStatus",
                            "AddedBy", "AddedDate", "UpdatedBy", "UpdatedDate")
    SELECT varOrganizationId, t."MenuId", t."SubMenuKey", t."Label", t."Order", 'A',
           'SYSTEM', localtimestamp, 'SYSTEM', localtimestamp
    FROM "sys_sub_menu" t
    WHERE t."RecordStatus" <> 'D'
      AND NOT EXISTS (SELECT 1 FROM "sub_menu" s
                      WHERE s."OrganizationId" = varOrganizationId AND s."SubMenuKey" = t."SubMenuKey");
END;
$$;

-- SUPERADMIN and ADMIN get every action on every page (PAGE menus and the organization's sub-menus),
-- ViewType SELF, Title "<Role> – <page label>" — only where that role never had a permission for the
-- page (deleted ones are not re-added).
DROP ROUTINE IF EXISTS "assign_default_permissions";
CREATE OR REPLACE PROCEDURE "assign_default_permissions"(varOrganizationId bigint)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO "role_permission" ("OrganizationId", "RoleId", "MenuId", "SubMenuId", "Title", "Page", "IsOption",
                                   "IsPageAllow", "Add", "Edit", "Delete", "Export", "ViewType", "RecordStatus",
                                   "AddedBy", "AddedDate", "UpdatedBy", "UpdatedDate")
    SELECT varOrganizationId, r."RoleId", p."MenuId", p."SubMenuId",
           left(initcap(r."RoleName") || ' – ' || p."Label", 50), NULL, NULL,
           '1', '1', '1', '1', '1', 'SELF', 'A',
           'SYSTEM', localtimestamp, 'SYSTEM', localtimestamp
    FROM "role" r
    CROSS JOIN (
        SELECT m."MenuId", NULL::bigint AS "SubMenuId", m."Menu" AS "Label"
        FROM "sys_menu" m
        WHERE m."MenuType" = 'PAGE' AND m."RecordStatus" <> 'D'
        UNION ALL
        SELECT s."MenuId", s."SubMenuId", s."Label"
        FROM "sub_menu" s
        JOIN "sys_menu" m ON m."MenuId" = s."MenuId" AND m."MenuType" = 'GROUP' AND m."RecordStatus" <> 'D'
        WHERE s."OrganizationId" = varOrganizationId AND s."RecordStatus" <> 'D'
    ) p
    WHERE r."OrganizationId" = varOrganizationId
      AND r."RoleId" IN (2, 7) -- SUPERADMIN, ADMIN
      AND r."RecordStatus" <> 'D'
      AND NOT EXISTS (
          SELECT 1 FROM "role_permission" rp
          WHERE rp."OrganizationId" = varOrganizationId AND rp."RoleId" = r."RoleId"
            AND rp."MenuId" = p."MenuId" AND coalesce(rp."SubMenuId", 0) = coalesce(p."SubMenuId", 0)
      );
END;
$$;

-- 7. Existing organizations.
DO $$
DECLARE
    org record;
BEGIN
    FOR org IN SELECT "OrganizationId" FROM "organization" WHERE "RecordStatus" <> 'D' LOOP
        CALL "assign_default_sub_menus"(org."OrganizationId");
        CALL "assign_default_permissions"(org."OrganizationId");
    END LOOP;
END $$;

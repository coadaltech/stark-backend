-- Staff permissions (specs/build/permissions/permission_spec.md §4.3): named sets of actions per page,
-- created per organization and assigned to staff (login."StaffPermissionId"). A person's action needs
-- their role permission AND their staff permission; a page without an entry in the set is decided by
-- the role alone. ViewType always comes from the role.
-- Replaces the earlier per-person switches (a staff_permission table keyed by LoginId), which held no data.

-- 1. Drop the earlier per-person table, only if it still has that shape (so re-running is safe).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'staff_permission' AND column_name = 'LoginId') THEN
        DROP TABLE "staff_permission" CASCADE;
    END IF;
END $$;
DROP FUNCTION IF EXISTS "staff_permission_check"() CASCADE;

-- 2. The named sets.
CREATE TABLE IF NOT EXISTS "staff_permission" (
    "StaffPermissionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OrganizationId" bigint NOT NULL REFERENCES "organization" ("OrganizationId") ON DELETE CASCADE,
    "Title" varchar(50) NOT NULL,
    "RecordStatus" char(1) NOT NULL,
    "AddedBy" varchar(50) NOT NULL,
    "AddedDate" timestamp NOT NULL,
    "UpdatedBy" varchar(50) NOT NULL,
    "UpdatedDate" timestamp NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "staff_permission_title_key"
    ON "staff_permission" ("OrganizationId", lower("Title")) WHERE "RecordStatus" <> 'D';

-- 3. Actions per page of a set ('1' = allowed, '0' = not). Rows are replaced as a whole when a set is
--    saved. Page = a PAGE menu (SubMenuId NULL) or a sub-menu of a GROUP menu in the set's organization.
CREATE TABLE IF NOT EXISTS "staff_permission_page" (
    "StaffPermissionPageId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StaffPermissionId" bigint NOT NULL REFERENCES "staff_permission" ("StaffPermissionId") ON DELETE CASCADE,
    "MenuId" bigint NOT NULL REFERENCES "sys_menu" ("MenuId"),
    "SubMenuId" bigint REFERENCES "sub_menu" ("SubMenuId") ON DELETE CASCADE,
    "IsPageAllow" varchar(1) NOT NULL CHECK ("IsPageAllow" IN ('0', '1')),
    "Add" varchar(1) NOT NULL CHECK ("Add" IN ('0', '1')),
    "Edit" varchar(1) NOT NULL CHECK ("Edit" IN ('0', '1')),
    "Delete" varchar(1) NOT NULL CHECK ("Delete" IN ('0', '1')),
    "Export" varchar(1) NOT NULL CHECK ("Export" IN ('0', '1'))
);
CREATE UNIQUE INDEX IF NOT EXISTS "staff_permission_page_key"
    ON "staff_permission_page" ("StaffPermissionId", "MenuId", coalesce("SubMenuId", 0));

CREATE OR REPLACE FUNCTION "staff_permission_page_check"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    menuType varchar;
BEGIN
    SELECT m."MenuType" INTO menuType FROM "sys_menu" m WHERE m."MenuId" = NEW."MenuId";
    IF menuType IS NULL THEN
        RAISE EXCEPTION 'Menu % does not exist', NEW."MenuId"
            USING ERRCODE = 'foreign_key_violation', CONSTRAINT = 'staff_permission_page_menu';
    ELSIF menuType = 'PAGE' AND NEW."SubMenuId" IS NOT NULL THEN
        RAISE EXCEPTION 'Menu % has no sub-menus', NEW."MenuId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'staff_permission_page_page_menu';
    ELSIF menuType = 'GROUP' AND NOT EXISTS (
        SELECT 1 FROM "sub_menu" s
        JOIN "staff_permission" sp ON sp."StaffPermissionId" = NEW."StaffPermissionId"
        WHERE s."SubMenuId" = NEW."SubMenuId" AND s."MenuId" = NEW."MenuId" AND s."OrganizationId" = sp."OrganizationId"
    ) THEN
        RAISE EXCEPTION 'A sub-menu of menu % in this organization is required', NEW."MenuId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'staff_permission_page_group_sub_menu';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "staff_permission_page_check" ON "staff_permission_page";
CREATE TRIGGER "staff_permission_page_check" BEFORE INSERT OR UPDATE ON "staff_permission_page"
    FOR EACH ROW EXECUTE FUNCTION "staff_permission_page_check"();

-- 4. The staff permission assigned to a staff member (NULL = role permissions only).
ALTER TABLE "login" ADD COLUMN IF NOT EXISTS "StaffPermissionId" bigint
    REFERENCES "staff_permission" ("StaffPermissionId") ON DELETE SET NULL;

-- Only a set of the staff member's own organization.
CREATE OR REPLACE FUNCTION "login_staff_permission_check"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."StaffPermissionId" IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM "staff_permission" sp
        WHERE sp."StaffPermissionId" = NEW."StaffPermissionId"
          AND sp."OrganizationId" IS NOT DISTINCT FROM NEW."OrganizationId"
    ) THEN
        RAISE EXCEPTION 'Staff permission % does not belong to organization %', NEW."StaffPermissionId", NEW."OrganizationId"
            USING ERRCODE = 'check_violation', CONSTRAINT = 'login_staff_permission_org';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "login_staff_permission_check" ON "login";
CREATE TRIGGER "login_staff_permission_check" BEFORE INSERT OR UPDATE OF "StaffPermissionId", "OrganizationId" ON "login"
    FOR EACH ROW EXECUTE FUNCTION "login_staff_permission_check"();
